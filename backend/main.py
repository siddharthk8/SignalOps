import tomllib
from pathlib import Path
from typing import cast

from fastapi import FastAPI, Request
from fastapi.concurrency import asynccontextmanager
from fastapi.exceptions import RequestValidationError
from fastapi.middleware.cors import CORSMiddleware
from fastapi.routing import APIRoute
from starlette.exceptions import HTTPException as StarletteHTTPException
from starlette.types import ExceptionHandler

from app.api.v1.router import v1_router
from app.core.config import settings
from app.core.exceptions import (
    general_http_exception_handler,
    unhandled_exception_handler,
    validation_exception_handler,
)
from app.db.core import engine


@asynccontextmanager
async def lifespan(app: FastAPI):
    yield  # app runs here
    # shutdown logic
    await engine.dispose()


# Generate OpenAPI operationIds from FastAPI route names instead of
# the default autogenerated IDs. Ensure all route names (function names)
# must be unique across the entire application.
def custom_generate_unique_id(route: APIRoute) -> str:
    return route.name


PYPROJECT = Path(__file__).resolve().parent / "pyproject.toml"
with PYPROJECT.open("rb") as f:
    __version__ = tomllib.load(f)["project"]["version"]


IS_PRODUCTION = settings.env == "production"

app = FastAPI(
    title="SignalOps",
    description="SignalOps is a log intelligence and incident analysis platform that converts raw system logs into meaningful insights.",
    version=__version__,
    lifespan=lifespan,
    docs_url=None if IS_PRODUCTION else "/docs",
    redoc_url=None if IS_PRODUCTION else "/redoc",
    openapi_url=None if IS_PRODUCTION else "/openapi.json",
    generate_unique_id_function=custom_generate_unique_id,
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=settings.cors_origins,
    allow_methods=["*"],
    allow_headers=["*"],
)


@app.middleware("http")
async def security_headers(request: Request, call_next):
    response = await call_next(request)

    response.headers["X-Frame-Options"] = "SAMEORIGIN"
    response.headers["X-Content-Type-Options"] = "nosniff"
    response.headers["Referrer-Policy"] = "strict-origin-when-cross-origin"

    # HSTS must only be used in production over HTTPS.
    # Behind reverse proxies (e.g. Nginx/ALB), request.url.scheme may not
    # reflect the original protocol, we skip HSTS for localhost and
    # assume all other hosts are served over HTTPS.
    if request.url.hostname not in ("localhost", "127.0.0.1"):
        response.headers["Strict-Transport-Security"] = (
            "max-age=63072000; includeSubDomains"
        )

    return response


app.include_router(v1_router, prefix="/api/v1")

# Handle Exceptions
app.add_exception_handler(
    StarletteHTTPException,
    cast(ExceptionHandler, general_http_exception_handler),
)
app.add_exception_handler(
    RequestValidationError,
    cast(ExceptionHandler, validation_exception_handler),
)
app.add_exception_handler(Exception, unhandled_exception_handler)
