    POSSIBLE_ACCOUNT_COMPROMISE = "POSSIBLE_ACCOUNT_COMPROMISE"
    EXCESSIVE_AUTH_FAILURES = "EXCESSIVE_AUTH_FAILURES"
    SUSPICIOUS_SESSION_ACTIVITY = "SUSPICIOUS_SESSION_ACTIVITY"
