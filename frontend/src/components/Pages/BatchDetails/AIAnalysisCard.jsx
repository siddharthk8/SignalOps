import { BrainCircuit, Lightbulb, ShieldAlert, Sparkles, Target } from "lucide-react";

const severityClasses = {
	low: "bg-success/10 text-success",
	medium: "bg-warning/10 text-warning",
	high: "bg-error/10 text-error",
	critical: "bg-error text-white",
};

function Section({ icon: Icon, title, children }) {
	return (
		<div>
			<div className="mb-3 flex items-center gap-2">
				<Icon size={17} className="text-primary" />

				<h3 className="font-semibold">{title}</h3>
			</div>

			{children}
		</div>
	);
}

function AIAnalysisCard({ analyses }) {
	if (!analyses.length) {
		return (
			<section className="bg-surface border-border overflow-hidden rounded-md border">
				<div className="border-border flex items-center justify-between border-b px-5 py-4">
					<div>
						<h2 className="text-base font-semibold">AI Operational Analysis</h2>

						<p className="text-t-muted mt-1 text-sm">
							No AI analysis was generated for this batch.
						</p>
					</div>

					<div className="bg-primary/10 text-primary flex h-9 w-9 items-center justify-center rounded-md">
						<BrainCircuit size={18} />
					</div>
				</div>

				<div className="px-5 py-12 text-center">
					<BrainCircuit size={28} className="text-t-muted mx-auto mb-3" />

					<h3 className="font-medium">No AI Analysis Available</h3>
				</div>
			</section>
		);
	}

	return (
		<section className="space-y-5">
			{analyses.map((analysis) => (
				<div
					key={analysis.id}
					className="bg-surface border-border overflow-hidden rounded-md border"
				>
					<div className="border-border flex items-center justify-between border-b px-5 py-4">
						<div>
							<div className="flex flex-wrap items-center gap-2">
								<h2 className="text-base font-semibold">AI Operational Analysis</h2>

								<span
									className={`rounded-md px-2 py-0.5 text-[11px] font-medium ${
										severityClasses[analysis.severity]
									}`}
								>
									{analysis.severity.toUpperCase()}
								</span>
							</div>

							<p className="text-t-muted mt-1 text-sm">Generated by Amazon Bedrock</p>
						</div>

						<div className="bg-primary/10 text-primary flex h-10 w-10 items-center justify-center rounded-md">
							<BrainCircuit size={20} />
						</div>
					</div>

					<div className="space-y-8 p-5">
						<Section icon={Sparkles} title="Executive Summary">
							<p className="text-t-secondary leading-7">{analysis.summary}</p>
						</Section>

						<Section icon={Target} title="Root Cause">
							<p className="text-t-secondary leading-7">{analysis.root_cause}</p>
						</Section>

						<div className="grid gap-8 lg:grid-cols-2">
							<Section icon={ShieldAlert} title="Business Impact">
								<ul className="space-y-3">
									{JSON.parse(analysis.business_impact).map((item, index) => (
										<li key={index} className="flex items-start gap-3">
											<div className="bg-error mt-2 h-1.5 w-1.5 rounded-full" />

											<span className="text-sm leading-6">{item}</span>
										</li>
									))}
								</ul>
							</Section>

							<Section icon={Lightbulb} title="Recommendations">
								<ul className="space-y-3">
									{JSON.parse(analysis.recommendations).map((item, index) => (
										<li key={index} className="flex items-start gap-3">
											<div className="bg-primary text-primary-foreground flex h-5 w-5 shrink-0 items-center justify-center rounded-full text-[11px] font-semibold">
												{index + 1}
											</div>

											<span className="text-sm leading-6">{item}</span>
										</li>
									))}
								</ul>
							</Section>
						</div>

						<div className="border-border grid gap-6 border-t pt-5 sm:grid-cols-2">
							<div>
								<p className="text-t-muted text-[11px] tracking-wide uppercase">
									Incident Type
								</p>

								<p className="mt-1 text-sm font-medium">
									{analysis.incident_type
										.replaceAll("_", " ")
										.replace(/\b\w/g, (c) => c.toUpperCase())}
								</p>
							</div>

							<div className="sm:text-right">
								<p className="text-t-muted text-[11px] tracking-wide uppercase">
									AI Confidence
								</p>

								<p className="text-primary mt-1 text-2xl font-semibold">
									{Math.round(analysis.confidence * 100)}%
								</p>
							</div>
						</div>
					</div>
				</div>
			))}
		</section>
	);
}

export default AIAnalysisCard;
